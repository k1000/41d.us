#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const checkOnly = process.argv.includes("--check");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "packages/helper/client/41d.js");
const targetPath = resolve(root, "packages/helper/src/client-script.ts");

const source = await readFile(sourcePath, "utf8");
const output = renderClientScript(source);

if (checkOnly) {
  const current = await readFile(targetPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error(`${targetPath} is out of date. Run pnpm generate:client-script.`);
    process.exit(1);
  }
  console.log(`${targetPath} is up to date`);
} else {
  await writeFile(targetPath, output);
  console.log(`generated ${targetPath}`);
}

function renderClientScript(source) {
  return `/**
 * The 41d.us tiny encrypted client script, served at /client/41d.js.
 *
 * Generated from packages/helper/client/41d.js by scripts/generate-client-script.mjs.
 * Do not edit this file directly; edit the standalone script and regenerate.
 */
export const clientScript: string = ${JSON.stringify(source)};
`;
}
